import fs from 'node:fs';
import assert from 'node:assert/strict';
const root=process.cwd();
const read=n=>fs.readFileSync(root+'/supabase/functions/'+n+'/index.ts','utf8');
const start=read('marketing-oauth-start');
const cb=read('marketing-oauth-callback');
const discover=read('google-ads-discover-accounts');
const select=read('google-ads-select-account');
const sync=read('google-ads-sync-readonly');
const ready=read('marketing-connector-readiness');
const status=read('marketing-integration-status');
let n=0;const ok=(c,m)=>{assert.ok(c,m);n++;console.log('PASS '+m)};
for(const src of [start,discover,select,sync,ready,status]){
 ok(src.includes('auth.getUser'),'authenticated marketing endpoint validates user JWT');
 ok(src.includes('Owner access required'),'authenticated marketing endpoint is owner-only');
}
ok(start.includes('code_challenge_method","S256'),'OAuth start uses PKCE S256');
ok(start.includes('state_hash:await sha256Hex(state)'),'OAuth state is stored hashed');
ok(start.includes('10*60*1000'),'OAuth state expires in ten minutes');
ok(start.includes('prompt","consent'),'OAuth start requests consent for refresh token');
ok(cb.includes('req.method!=="GET"'),'OAuth callback only accepts GET');
ok(cb.includes('^[A-Za-z0-9_-]{40,100}$'),'OAuth callback validates state shape');
ok(cb.includes('code.length>4096'),'OAuth callback bounds auth code size');
ok(cb.includes('consumed_at'),'OAuth callback consumes state once');
ok(cb.includes('gt("expires_at"'),'OAuth callback checks state expiry');
ok(cb.includes('redirect_uri||"")!==CALLBACK'),'OAuth callback binds stored redirect URI');
ok(cb.includes('code_verifier:String(st.code_verifier||"")'),'OAuth callback uses PKCE verifier');
ok(cb.includes('safeReturnTo'),'OAuth callback restricts return origin');
ok(cb.includes('store_marketing_oauth_secret'),'OAuth callback stores refresh token via secret RPC');
ok(!cb.includes('console.log(token'),'OAuth callback never logs token payload');
ok(discover.includes('write_enabled:false'),'account discovery declares external writes disabled');
ok(select.includes('external_mutation:false'),'account selection declares no external mutation');
ok(sync.includes('googleAds:searchStream'),'Google Ads sync uses searchStream reads');
ok(!/campaigns:mutate|campaignBudgets:mutate|adGroupCriteria:mutate/.test(sync),'Google Ads sync contains no mutate API');
ok(status.includes('provider,status,granted_scopes,token_expires_at,connected_at,last_error,updated_at'),'status selects safe OAuth metadata only');
ok(!status.includes('credential_ref'),'status does not select credential reference');
ok(!status.includes('account_meta'),'status does not select account metadata');
ok(ready.includes('secrets_exposed:false'),'readiness never exposes secret values');
console.log(n+'/'+n+' marketing OAuth security assertions passed');
