import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'..');
const ai=fs.readFileSync(path.join(root,'supabase/functions/ai-manager-tools/index.ts'),'utf8');
const ui=fs.readFileSync(path.join(root,'index.html'),'utf8');
const checks=[]; const ok=(name,test)=>checks.push([name,!!test]);
ok('delegates to read-only gateway',ai.includes('/functions/v1/google-ads-readonly'));
ok('requests summary tool',ai.includes('tool:"summary"'));
ok('stale message removed',!ai.includes('reporting sync is not implemented yet'));
ok('marks result read-only',ai.includes('read_only:true'));
ok('records source gateway',ai.includes('source:"google-ads-readonly"'));
ok('preserves upstream audit id',ai.includes('upstream_action_id:payload.actionId'));
ok('supports customer filter',ai.includes('customer_id:input.customer_id'));
ok('supports campaign filter',ai.includes('campaign_id:input.campaign_id'));
ok('UI isolates optional failures',ui.includes('Promise.allSettled'));
ok('UI has READ ONLY badge',ui.includes('READ ONLY'));
ok('UI handles zero synced rows',ui.includes('NO SYNCED ROWS'));
for(const field of ['campaigns','impressions','clicks','cost','conversions','ctr_percent','avg_cpc','attributed_leads']) ok('UI metric '+field,ui.includes(field));
const renderer=ui.match(/function renderAiManagerAds\(b,a\)\{[\s\S]*?\n\}/)?.[0]||'';
ok('renderer has no mutation onclick',!/(onclick|callAiManagerTool)[^\n]*(pause_campaign|launch_campaign|optimize_campaign|budget|bidding|keyword)/i.test(renderer));
ok('backend branch has no mutation tool',!/(pause_campaign|launch_campaign|optimize_campaign|set_budget|set_bidding|add_keyword)/.test(ai.match(/else if\(tool==="get_google_ads_summary"\)[^\n]*/)?.[0]||''));
const failed=checks.filter(([,pass])=>!pass); for(const [name,pass] of checks) console.log(`${pass?'PASS':'FAIL'} ${name}`);
console.log(`${checks.length-failed.length}/${checks.length} assertions passed`); if(failed.length) process.exit(1);